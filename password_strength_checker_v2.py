MIN_LENGTH = 8
SPECIAL_CHARS = "@#$%&!"
MAX_TRIES = 3


def check_password(passw):
    """Return a dictionary showing which rules the password passes."""
    rules = {
        f"At least {MIN_LENGTH} characters": len(passw) >= MIN_LENGTH,
        "An uppercase letter": False,
        "A lowercase letter": False,
        "A number": False,
        f"A special character ({SPECIAL_CHARS})": False,
    }

    for char in passw:
        if char.isupper():
            rules["An uppercase letter"] = True
        if char.islower():
            rules["A lowercase letter"] = True
        if char.isdigit():
            rules["A number"] = True
        if char in SPECIAL_CHARS:
            rules[f"A special character ({SPECIAL_CHARS})"] = True

    return rules


def strength(passed, total):
    if passed == total:
        return "Strong"
    elif passed >= total - 2:
        return "Medium"
    return "Weak"

for attempt in range(1, MAX_TRIES + 1):
    passw = input(f"\nEnter a Password (try {attempt}/{MAX_TRIES}): ")
    rules = check_password(passw)
    passed = sum(rules.values())

    print()
    for rule, ok in rules.items():
        mark = "✔" if ok else "✘"
        print(f"  {mark}  {rule}")

    print(f"\nStrength: {strength(passed, len(rules))}")

    if passed == len(rules):
        print("Password Accepted. Well done!")
        break
    elif attempt < MAX_TRIES:
        print("Almost there, please try again")
else:
    print("No attempts left. Please try again later")

